import fs from 'fs';
import path from 'path';
import dotenv from 'dotenv';

dotenv.config({ override: true });

async function runPostBuild() {
  const distDir = path.resolve(process.cwd(), 'dist');
  const distIndexPath = path.join(distDir, 'index.html');
  const distShellPath = path.join(distDir, '_shell.html');
  const builtShellModulePath = path.resolve(process.cwd(), 'api', '_built_shell.ts');

  if (!fs.existsSync(distIndexPath)) {
    console.warn('[postbuild-seo] dist/index.html not found, skipping post-build generation.');
    return;
  }

  const cleanShellHtml = fs.readFileSync(distIndexPath, 'utf-8');

  // 1. Зберігаємо чистий Vite-шаблон із хешованими /assets/*.js та /assets/*.css
  // у dist/_shell.html та api/_built_shell.ts для динамічного SSR через /api/render-page
  fs.writeFileSync(distShellPath, cleanShellHtml, 'utf-8');
  fs.writeFileSync(
    builtShellModulePath,
    `// Auto-generated by scripts/postbuild-seo.mjs during npm run build\nexport const BUILT_HTML_SHELL: string = ${JSON.stringify(cleanShellHtml)};\n`,
    'utf-8'
  );

  // КРИТИЧНО: Видаляємо статичний dist/index.html, щоб на Vercel та інших платформах
  // головна сторінка "/" ЗАВЖДИ проходила через динамічний серверний рендер (/api/render-page)
  // і ніколи не віддавала застарілий знімок учорашніх матеріалів часу білду.
  try {
    if (fs.existsSync(distIndexPath)) {
      fs.unlinkSync(distIndexPath);
      console.log('[postbuild-seo] Removed static dist/index.html (dynamic SSR active on "/" via /api/render-page).');
    }
  } catch (err) {
    console.warn('[postbuild-seo] Could not remove dist/index.html:', err);
  }

  // 2. Гарантуємо наявність статичного dist/robots.txt, dist/favicon.ico та dist/favicon.svg
  const publicRobotsPath = path.resolve(process.cwd(), 'public', 'robots.txt');
  const distRobotsPath = path.join(distDir, 'robots.txt');
  if (fs.existsSync(publicRobotsPath)) {
    fs.copyFileSync(publicRobotsPath, distRobotsPath);
    console.log('[postbuild-seo] Copied public/robots.txt -> dist/robots.txt');
  }

  const publicIcoPath = path.resolve(process.cwd(), 'public', 'favicon.ico');
  const distIcoPath = path.join(distDir, 'favicon.ico');
  if (fs.existsSync(publicIcoPath)) {
    fs.copyFileSync(publicIcoPath, distIcoPath);
    console.log('[postbuild-seo] Copied public/favicon.ico -> dist/favicon.ico');
  }

  const publicSvgPath = path.resolve(process.cwd(), 'public', 'favicon.svg');
  const distSvgPath = path.join(distDir, 'favicon.svg');
  if (fs.existsSync(publicSvgPath)) {
    fs.copyFileSync(publicSvgPath, distSvgPath);
    console.log('[postbuild-seo] Copied public/favicon.svg -> dist/favicon.svg');
  }

  // 3. Оновлюємо локальні файли sitemap.xml та news-sitemap.xml у public/,
  // але видаляємо статичні копії з dist/, щоб /sitemap.xml та /news-sitemap.xml
  // завжди генерувалися динамічно з актуальної БД.
  try {
    const { fetchSitemapSourceData, collectSitemapEntries, buildSitemapDocuments } = await import('../api/sitemap.ts');
    const sourceData = await fetchSitemapSourceData();
    const sitemapEntries = collectSitemapEntries(sourceData);
    const docs = buildSitemapDocuments(sitemapEntries);

    fs.writeFileSync(path.resolve(process.cwd(), 'public', 'sitemap.xml'), docs.rootXml, 'utf-8');
    if (docs.isIndex && docs.partsXml.length > 0) {
      docs.partsXml.forEach((partXml, idx) => {
        fs.writeFileSync(path.resolve(process.cwd(), 'public', `sitemap-${idx + 1}.xml`), partXml, 'utf-8');
      });
    }
    console.log(`[postbuild-seo] Updated public/sitemap.xml with ${sitemapEntries.length} entries.`);
  } catch (err) {
    console.warn('[postbuild-seo] Notice: sitemap generation notice (runtime handler ready):', err);
  }

  try {
    const { fetchArticlesStrict } = await import('../api/sitemap.ts');
    const { collectNewsSitemapEntries, renderNewsSitemapXml } = await import('../api/news-sitemap.ts');
    const articles = await fetchArticlesStrict();
    const newsEntries = collectNewsSitemapEntries(articles);
    const newsXml = renderNewsSitemapXml(newsEntries);

    fs.writeFileSync(path.resolve(process.cwd(), 'public', 'news-sitemap.xml'), newsXml, 'utf-8');
    console.log(`[postbuild-seo] Updated public/news-sitemap.xml with ${newsEntries.length} entries.`);
  } catch (err) {
    console.warn('[postbuild-seo] Notice: news-sitemap generation notice (runtime handler ready):', err);
  }

  try {
    const distFiles = fs.readdirSync(distDir);
    for (const file of distFiles) {
      if (/^(?:news-)?sitemap(?:-[^/]+)?\.xml$/i.test(file)) {
        fs.unlinkSync(path.join(distDir, file));
      }
    }
  } catch {}
}

runPostBuild();
